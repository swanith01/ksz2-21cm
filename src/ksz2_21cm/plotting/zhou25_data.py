def zhou5_anchor():
    """
    Fig.5 ell=800 peak, used as the anchor for the adhoc unit-normalisation
    scale factor in SNR_rigorous_v2.py / scripts/05_compute_snr_forecast.py.

    Returns
    -------
    (anchor_D_muK4, anchor_z) : float, float
    """
    fig5_800 = ZHOU_FIG5[800]
    i = np.argmax(fig5_800[:, 1])
    return float(fig5_800[i, 1]), float(fig5_800[i, 0])
